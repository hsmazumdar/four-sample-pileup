"""Dump frozen weights as C arrays for HLS / a tiny MCU firmware.

Do not invent DSP/LUT/ns here. Count them from the synthesis of *this* header.
"""

from __future__ import annotations

from pathlib import Path

from sparse_pileup.constants import (
    ADC_CHANNELS,
    CLIP_PRE,
    N_HIDDEN,
    N_SAMPLES,
    SAMPLE_STRIDE,
    TRIGGER_CHANNEL,
)
from sparse_pileup.dual_head import DualHeadDetector
from sparse_pileup.mlp import N_HID, N_IN


def _matrix(name: str, arr) -> str:
    rows = []
    for r in arr:
        body = ", ".join(f"{float(v):.8f}f" for v in r)
        rows.append(f"    {{ {body} }}")
    return f"static const float {name}[{arr.shape[0]}][{arr.shape[1]}] = {{\n" + ",\n".join(rows) + "\n};\n"


def save_c_header(model: DualHeadDetector, path: Path) -> None:
    p = model.pileup
    h = model.peak
    body = f"""/* Auto-generated by sparse_pileup.export_fpga.save_c_header
 * Dual 4-5-1 MLP, {N_SAMPLES} post-trigger samples, stride {SAMPLE_STRIDE}.
 * Trigger comparator: adc >= {TRIGGER_CHANNEL} (of {ADC_CHANNELS}).
 * Sigmoid: clip to ±{CLIP_PRE:g}, then LUT of 1/(1+exp(-x)).
 * MAC count: 31 per head, 62 if both heads are fully parallel.
 * Do not treat this comment as a measured FPGA resource report.
 */
#ifndef DUAL_HEAD_WEIGHTS_H
#define DUAL_HEAD_WEIGHTS_H

#define N_IN       {N_IN}
#define N_HIDDEN   {N_HID}
#define N_OUT      1
#define N_SAMPLES  {N_SAMPLES}
#define SAMPLE_STRIDE {SAMPLE_STRIDE}
#define TRIGGER_CHANNEL {TRIGGER_CHANNEL}
#define ADC_CHANNELS {ADC_CHANNELS}
#define CLIP_PRE   {CLIP_PRE:.1f}f
#define PILEUP_THRESHOLD 0.5f

{_matrix("PILEUP_WIJ", p.wij)}
{_matrix("PILEUP_WJK", p.wjk)}
{_matrix("PEAK_WIJ", h.wij)}
{_matrix("PEAK_WJK", h.wjk)}

#endif /* DUAL_HEAD_WEIGHTS_H */
"""
    Path(path).write_text(body, encoding="utf-8")
